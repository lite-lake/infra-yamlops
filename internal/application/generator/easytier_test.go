func TestGenerateEasyTierConfig_Shared(t *testing.T) {
	tmpDir := t.TempDir()
	gen := NewGenerator("prod", tmpDir)

	infra := &entity.InfraService{
		Name: "easytier-node5",
		Type: entity.InfraServiceTypeEasyTier,
		ServiceBase: entity.ServiceBase{
			Server: "srv-node5",
		},
		Image: "mirror.example.com/ghcr/easytier/easytier:v2.6.4",
		EasyTierConfig: &entity.EasyTierConfig{
			Role:          "shared",
			VirtualIP:     "10.72.0.11/24",
			NetworkName:   "lite-mesh-prod",
			NetworkSecret: *valueobject.NewSecretRefSecret("et_network_secret_prod"),
			Hostname:      "srv-node5",
			Listeners:     []string{"quic://0.0.0.0:11010"},
			Peers: []string{
				"quic://103.236.57.87:11010",
				"quic://103.236.53.189:11010",
			},
			Flags: entity.EasyTierFlags{
				LatencyFirst:          true,
				PrivateMode:           true,
				RelayNetworkWhitelist: "",
				RelayAllPeerRPC:       true,
			},
		},
	}

	config := &entity.Config{
		Secrets: []entity.Secret{{Name: "et_network_secret_prod", Value: "mesh-secret-prod"}},
	}

	if err := gen.generateEasyTierConfig(tmpDir, infra, config); err != nil {
		t.Fatalf("generateEasyTierConfig() error = %v", err)
	}

	t.Run("toml content", func(t *testing.T) {
		content, err := os.ReadFile(filepath.Join(tmpDir, "easytier-node5.easytier.toml"))
		if err != nil {
			t.Fatalf("failed to read easytier.toml: %v", err)
		}
		s := string(content)
		checks := []string{
			"# Auto-generated by yamlops, do not edit manually",
			`instance_name = "easytier-node5"`,
			`hostname = "srv-node5"`,
			`ipv4 = "10.72.0.11/24"`,
			"[network_identity]",
			`network_name = "lite-mesh-prod"`,
			`network_secret = "mesh-secret-prod"`,
			`listeners = ["quic://0.0.0.0:11010"]`,
			"[[peer]]",
			`uri = "quic://103.236.57.87:11010"`,
			`uri = "quic://103.236.53.189:11010"`,
			"[flags]",
			"latency_first = true",
			"private_mode = true",
			`relay_network_whitelist = ""`,
			"relay_all_peer_rpc = true",
			"no_listener = false",
		}
		for _, c := range checks {
			if !strings.Contains(s, c) {
				t.Errorf("easytier.toml missing %q\n---\n%s", c, s)
			}
		}
		if strings.Count(s, "[[peer]]") != 2 {
			t.Errorf("expected 2 [[peer]] sections, got %d", strings.Count(s, "[[peer]]"))
		}
		if idxListeners := strings.Index(s, "listeners = "); idxListeners < 0 || strings.Index(s, "[network_identity]") < idxListeners {
			t.Errorf("listeners must be a top-level key before [network_identity] (TOML table scope)\n%s", s)
		}
	})

	t.Run("compose content", func(t *testing.T) {
		content, err := os.ReadFile(filepath.Join(tmpDir, "easytier-node5.compose.yaml"))
		if err != nil {
			t.Fatalf("failed to read compose: %v", err)
		}
		s := string(content)
		checks := []string{
			"image: mirror.example.com/ghcr/easytier/easytier:v2.6.4",
			"container_name: yo-prod-easytier-node5",
			"network_mode: host",
			"privileged: true",
			"restart: always",
			"soft: 1048576",
			"hard: 1048576",
			"- ./easytier-node5.easytier.toml:/etc/easytier.toml:ro",
			"- -c",
			"- /etc/easytier.toml",
		}
		for _, c := range checks {
			if !strings.Contains(s, c) {
				t.Errorf("compose missing %q\n---\n%s", c, s)
			}
		}
		if strings.Contains(s, "yamlops-prod") {
			t.Errorf("host network compose should not reference yamlops-prod network\n%s", s)
		}
		if strings.Contains(s, "networks:") {
			t.Errorf("host network compose should not declare networks\n%s", s)
		}
		if strings.Contains(s, "deploy:") || strings.Contains(s, "resources:") {
			t.Errorf("compose without resources config should not emit deploy/resources\n%s", s)
		}
	})
}

func TestGenerateEasyTierConfig_Resources(t *testing.T) {
	tests := []struct {
		name        string
		resources   entity.ServiceResources
		wantChecks  []string
		wantMissing []string
	}{
		{
			name:      "cpu and memory",
			resources: entity.ServiceResources{CPU: "1", Memory: "256M"},
			wantChecks: []string{
				"deploy:",
				"resources:",
				"limits:",
				`cpus: "1"`,
				"memory: 256M",
			},
		},
		{
			name:       "memory only",
			resources:  entity.ServiceResources{Memory: "256M"},
			wantChecks: []string{"limits:", "memory: 256M"},
			wantMissing: []string{
				"cpus:",
			},
		},
		{
			name:      "cpu only",
			resources: entity.ServiceResources{CPU: "0.5"},
			wantChecks: []string{
				"limits:",
				`cpus: "0.5"`,
			},
			wantMissing: []string{
				"memory:",
			},
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			tmpDir := t.TempDir()
			gen := NewGenerator("dev", tmpDir)

			infra := &entity.InfraService{
				Name: "easytier-node1",
				Type: entity.InfraServiceTypeEasyTier,
				ServiceBase: entity.ServiceBase{
					Server: "srv-node1",
				},
				Image: "mirror.example.com/ghcr/easytier/easytier:v2.6.4",
				EasyTierConfig: &entity.EasyTierConfig{
					Role:          "leaf",
					VirtualIP:     "10.71.0.191/24",
					NetworkName:   "lite-mesh-dev",
					NetworkSecret: *valueobject.NewSecretRefSecret("et_network_secret_dev"),
					Peers:         []string{"quic://154.37.215.114:11010"},
				},
				Resources: tt.resources,
			}

			config := &entity.Config{
				Secrets: []entity.Secret{{Name: "et_network_secret_dev", Value: "mesh-secret-dev"}},
			}

			if err := gen.generateEasyTierConfig(tmpDir, infra, config); err != nil {
				t.Fatalf("generateEasyTierConfig() error = %v", err)
			}

			content, err := os.ReadFile(filepath.Join(tmpDir, "easytier-node1.compose.yaml"))
			if err != nil {
				t.Fatalf("failed to read compose: %v", err)
			}
			s := string(content)
			for _, c := range tt.wantChecks {
				if !strings.Contains(s, c) {
					t.Errorf("compose missing %q\n---\n%s", c, s)
				}
			}
			for _, c := range tt.wantMissing {
				if strings.Contains(s, c) {
					t.Errorf("compose should not contain %q\n---\n%s", c, s)
				}
			}
		})
	}
}

