func TestGenerateEasyTierConfig_MissingSecret(t *testing.T) {
	tmpDir := t.TempDir()
	gen := NewGenerator("prod", tmpDir)

	infra := &entity.InfraService{
		Name:        "easytier-node5",
		Type:        entity.InfraServiceTypeEasyTier,
		ServiceBase: entity.ServiceBase{Server: "srv-node5"},
		Image:       "easytier:v2.6.4",
		EasyTierConfig: &entity.EasyTierConfig{
			Role:          "shared",
			VirtualIP:     "10.72.0.11/24",
			NetworkName:   "lite-mesh-prod",
			NetworkSecret: *valueobject.NewSecretRefSecret("et_network_secret_prod"),
			Listeners:     []string{"quic://0.0.0.0:11010"},
		},
	}

	config := &entity.Config{Secrets: nil}

	err := gen.generateEasyTierConfig(tmpDir, infra, config)
	if err == nil {
		t.Fatal("expected error for missing secret")
	}
	if !strings.Contains(err.Error(), "network_secret") {
		t.Errorf("error should mention network_secret, got: %v", err)
	}
}
