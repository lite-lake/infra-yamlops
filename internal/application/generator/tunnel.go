package generator

import (
	"fmt"
	"os"
	"path/filepath"
	"strconv"
	"strings"

	"github.com/lite-lake/infra-yamlops/internal/application/generator/compose"
	"github.com/lite-lake/infra-yamlops/internal/constants"
	"github.com/lite-lake/infra-yamlops/internal/domain/entity"
)

const (
	defaultTunnelBindPort  = 30070
	defaultTunnelVhostPort = 80
)

func (g *Generator) generateTunnelServerConfig(serverDir string, infra *entity.InfraService, config *entity.Config) error {
	ts := infra.TunnelServerConfig

	bindPort := ts.Ports.BindPort
	if bindPort == 0 {
		bindPort = defaultTunnelBindPort
	}
	vhostPort := ts.Ports.VhostHTTPPort
	if vhostPort == 0 {
		vhostPort = defaultTunnelVhostPort
	}

	var sb strings.Builder
	sb.WriteString("# Auto-generated by yamlops, do not edit manually\n\n")

	sb.WriteString("bindAddr = \"0.0.0.0\"\n")
	sb.WriteString(fmt.Sprintf("bindPort = %d\n", bindPort))
	sb.WriteString(fmt.Sprintf("vhostHTTPPort = %d\n", vhostPort))
	sb.WriteString("vhostHTTPSPort = 0\n\n")

	secrets := config.GetSecretsMap()
	authToken, err := ts.AuthToken.Resolve(secrets)
	if err != nil {
		return fmt.Errorf("failed to resolve auth_token for %s: %w", infra.Name, err)
	}
	sb.WriteString("auth.method = \"token\"\n")
	sb.WriteString(fmt.Sprintf("auth.token = \"%s\"\n\n", authToken))

	sb.WriteString("log.to = \"console\"\n")
	sb.WriteString("log.level = \"info\"\n")
	sb.WriteString("log.maxDays = 7\n\n")

	sb.WriteString("# Only allow http/https proxies, no TCP port forwarding\n")
	sb.WriteString("allowPorts = []\n\n")

	sb.WriteString("transport.tls.force = true\n")

	configFile := filepath.Join(serverDir, fmt.Sprintf("%s.frps.toml", infra.Name))
	if err := os.WriteFile(configFile, []byte(sb.String()), constants.FilePermissionConfig); err != nil {
		return fmt.Errorf("failed to write frps config: %w", err)
	}

	composeContent, err := g.generateTunnelServerCompose(infra, bindPort)
	if err != nil {
		return err
	}
	composeFile := filepath.Join(serverDir, fmt.Sprintf("%s.compose.yaml", infra.Name))
	return os.WriteFile(composeFile, []byte(composeContent), constants.FilePermissionConfig)
}

func (g *Generator) generateTunnelServerCompose(infra *entity.InfraService, bindPort int) (string, error) {
	networks := infra.Networks
	if len(networks) == 0 {
		networks = []string{fmt.Sprintf("yamlops-%s", g.env)}
	}

	configVolume := fmt.Sprintf("./%s.frps.toml:/app/configs/frps.toml:ro", infra.Name)

	composeSvc := &compose.ComposeService{
		Name:       infra.Name,
		Image:      infra.Image,
		Ports:      []string{fmt.Sprintf("%d:%d", bindPort, bindPort)},
		Volumes:    []string{configVolume},
		Networks:   networks,
		ExtraHosts: []string{constants.HostDockerGateway},
	}

	return g.composeGen.Generate(composeSvc, g.env)
}

func (g *Generator) generateTunnelClientConfig(serverDir string, infra *entity.InfraService, config *entity.Config) error {
	tc := infra.TunnelClientConfig

	serverHost, serverPort := splitServerAddr(tc.ServerAddr)

	var sb strings.Builder
	sb.WriteString("# Auto-generated by yamlops, do not edit manually\n\n")

	sb.WriteString(fmt.Sprintf("serverAddr = \"%s\"\n", serverHost))
	sb.WriteString(fmt.Sprintf("serverPort = %d\n\n", serverPort))

	secrets := config.GetSecretsMap()
	authToken, err := tc.AuthToken.Resolve(secrets)
	if err != nil {
		return fmt.Errorf("failed to resolve auth_token for %s: %w", infra.Name, err)
	}
	sb.WriteString("auth.method = \"token\"\n")
	sb.WriteString(fmt.Sprintf("auth.token = \"%s\"\n\n", authToken))

	sb.WriteString("loginFailExit = false\n")
	sb.WriteString("transport.tls.enable = true\n")
	sb.WriteString("transport.poolCount = 2\n\n")

	sb.WriteString("log.to = \"console\"\n")
	sb.WriteString("log.level = \"info\"\n")
	sb.WriteString("log.maxDays = 7\n\n")

	for _, p := range tc.Proxies {
		localIP, localPort := splitLocalAddr(p.LocalAddr)
		sb.WriteString("[[proxies]]\n")
		sb.WriteString(fmt.Sprintf("name = \"%s\"\n", p.Name))
		sb.WriteString(fmt.Sprintf("type = \"%s\"\n", p.Type))
		sb.WriteString(fmt.Sprintf("localIP = \"%s\"\n", localIP))
		sb.WriteString(fmt.Sprintf("localPort = %s\n", localPort))
		if p.Type == "http" || p.Type == "https" {
			sb.WriteString(fmt.Sprintf("customDomains = %s\n", formatTomlArray(p.CustomDomains)))
		}
		if p.Type == "tcp" {
			sb.WriteString(fmt.Sprintf("remotePort = %d\n", p.RemotePort))
		}
		sb.WriteString("\n")
	}

	configFile := filepath.Join(serverDir, fmt.Sprintf("%s.frpc.toml", infra.Name))
	if err := os.WriteFile(configFile, []byte(sb.String()), constants.FilePermissionConfig); err != nil {
		return fmt.Errorf("failed to write frpc config: %w", err)
	}

	composeContent, err := g.generateTunnelClientCompose(infra)
	if err != nil {
		return err
	}
	composeFile := filepath.Join(serverDir, fmt.Sprintf("%s.compose.yaml", infra.Name))
	return os.WriteFile(composeFile, []byte(composeContent), constants.FilePermissionConfig)
}

func (g *Generator) generateTunnelClientCompose(infra *entity.InfraService) (string, error) {
	networks := infra.Networks
	if len(networks) == 0 {
		networks = []string{fmt.Sprintf("yamlops-%s", g.env)}
	}

	configVolume := fmt.Sprintf("./%s.frpc.toml:/app/configs/frpc.toml:ro", infra.Name)

	composeSvc := &compose.ComposeService{
		Name:       infra.Name,
		Image:      infra.Image,
		Volumes:    []string{configVolume},
		Networks:   networks,
		ExtraHosts: []string{constants.HostDockerGateway},
	}

	return g.composeGen.Generate(composeSvc, g.env)
}

func formatTomlArray(domains []string) string {
	quoted := make([]string, len(domains))
	for i, d := range domains {
		quoted[i] = fmt.Sprintf("\"%s\"", d)
	}
	return fmt.Sprintf("[%s]", strings.Join(quoted, ", "))
}

func splitServerAddr(addr string) (host string, port int) {
	host = addr
	port = defaultTunnelBindPort
	if idx := strings.LastIndex(addr, ":"); idx >= 0 {
		hostPart := addr[:idx]
		portPart := addr[idx+1:]
		if p, err := strconv.Atoi(portPart); err == nil && p > 0 {
			host = hostPart
			port = p
		}
	}
	return host, port
}

func splitLocalAddr(addr string) (ip string, port string) {
	ip = addr
	port = "80"
	if parts := strings.SplitN(addr, ":", 2); len(parts) == 2 {
		ip = parts[0]
		port = parts[1]
	}
	return ip, port
}
