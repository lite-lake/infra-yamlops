package generator

import (
	"fmt"
	"os"
	"path/filepath"
	"strconv"
	"strings"

	"github.com/lite-lake/infra-yamlops/internal/application/generator/compose"
	"github.com/lite-lake/infra-yamlops/internal/constants"
	"github.com/lite-lake/infra-yamlops/internal/domain/entity"
)

const (
	easyTierConfigPath = "/etc/easytier.toml"
	easyTierNoFile     = 1048576
)

// generateEasyTierConfig 生成 easytier 节点的 toml 配置 + docker-compose。
func (g *Generator) generateEasyTierConfig(serverDir string, infra *entity.InfraService, config *entity.Config) error {
	et := infra.EasyTierConfig

	secrets := config.GetSecretsMap()
	networkSecret, err := et.NetworkSecret.Resolve(secrets)
	if err != nil {
		return fmt.Errorf("failed to resolve network_secret for %s: %w", infra.Name, err)
	}

	var sb strings.Builder
	sb.WriteString("# Auto-generated by yamlops, do not edit manually\n\n")

	fmt.Fprintf(&sb, "instance_name = %q\n", infra.Name)
	if et.Hostname != "" {
		fmt.Fprintf(&sb, "hostname = %q\n", et.Hostname)
	}
	fmt.Fprintf(&sb, "ipv4 = %q\n", et.VirtualIP)
	sb.WriteString("\n")

	// listeners/peers 必须是顶层键（不能放在 [network_identity] 之后，否则会被归入该 table）
	if et.Role == "shared" {
		fmt.Fprintf(&sb, "listeners = %s\n", formatTomlArray(et.Listeners))
	} else {
		sb.WriteString("listeners = []\n")
	}
	sb.WriteString("\n")

	for _, p := range et.Peers {
		sb.WriteString("[[peer]]\n")
		fmt.Fprintf(&sb, "uri = %q\n", p)
		sb.WriteString("\n")
	}

	sb.WriteString("[network_identity]\n")
	fmt.Fprintf(&sb, "network_name = %q\n", et.NetworkName)
	fmt.Fprintf(&sb, "network_secret = %q\n", networkSecret)
	sb.WriteString("\n")

	flags := et.Flags
	noListener := flags.NoListener || et.Role == "leaf"
	sb.WriteString("[flags]\n")
	fmt.Fprintf(&sb, "latency_first = %s\n", strconv.FormatBool(flags.LatencyFirst))
	fmt.Fprintf(&sb, "private_mode = %s\n", strconv.FormatBool(flags.PrivateMode))
	fmt.Fprintf(&sb, "relay_network_whitelist = %q\n", flags.RelayNetworkWhitelist)
	fmt.Fprintf(&sb, "relay_all_peer_rpc = %s\n", strconv.FormatBool(flags.RelayAllPeerRPC))
	fmt.Fprintf(&sb, "no_listener = %s\n", strconv.FormatBool(noListener))
	sb.WriteString("\n")

	configFile := filepath.Join(serverDir, fmt.Sprintf("%s.easytier.toml", infra.Name))
	if err := os.WriteFile(configFile, []byte(sb.String()), constants.FilePermissionConfig); err != nil {
		return fmt.Errorf("failed to write easytier config: %w", err)
	}

	composeContent, err := g.generateEasyTierCompose(infra)
	if err != nil {
		return err
	}
	composeFile := filepath.Join(serverDir, fmt.Sprintf("%s.compose.yaml", infra.Name))
	return os.WriteFile(composeFile, []byte(composeContent), constants.FilePermissionConfig)
}

func (g *Generator) generateEasyTierCompose(infra *entity.InfraService) (string, error) {
	configVolume := fmt.Sprintf("./%s.easytier.toml:%s:ro", infra.Name, easyTierConfigPath)

	composeSvc := &compose.ComposeService{
		Name:        infra.Name,
		Image:       infra.Image,
		NetworkMode: "host",
		Privileged:  true,
		Ulimits: map[string]compose.Ulimit{
			"nofile": {Soft: easyTierNoFile, Hard: easyTierNoFile},
		},
		Command: []string{"-c", easyTierConfigPath},
		Volumes: []string{configVolume},
		Environment: map[string]string{
			"TZ": "Asia/Shanghai",
		},
		Resources: buildServiceResources(infra.Resources),
		Restart:   "always",
	}

	return g.composeGen.Generate(composeSvc, g.env)
}
