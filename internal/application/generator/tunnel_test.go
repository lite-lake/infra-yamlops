func TestFormatTomlArray(t *testing.T) {
	tests := []struct {
		name    string
		domains []string
		want    string
	}{
		{"single", []string{"a.example.com"}, "[\"a.example.com\"]"},
		{"multiple", []string{"a.com", "b.com"}, "[\"a.com\", \"b.com\"]"},
		{"empty", []string{}, "[]"},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			got := formatTomlArray(tt.domains)
			if got != tt.want {
				t.Errorf("formatTomlArray() = %s, want %s", got, tt.want)
			}
		})
	}
}

func TestSplitServerAddr(t *testing.T) {
	tests := []struct {
		name     string
		addr     string
		wantHost string
		wantPort int
	}{
		{"host:port", "gate-node5.mesh.example.net:30070", "gate-node5.mesh.example.net", 30070},
		{"host only defaults to 30070", "gate-node5.mesh.example.net", "gate-node5.mesh.example.net", 30070},
		{"ipv4 with port", "192.168.1.1:7000", "192.168.1.1", 7000},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			host, port := splitServerAddr(tt.addr)
			if host != tt.wantHost {
				t.Errorf("host = %q, want %q", host, tt.wantHost)
			}
			if port != tt.wantPort {
				t.Errorf("port = %d, want %d", port, tt.wantPort)
			}
		})
	}
}

