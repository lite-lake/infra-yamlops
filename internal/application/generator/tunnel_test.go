func TestGenerateTunnelServerConfig(t *testing.T) {
	tmpDir := t.TempDir()
	gen := NewGenerator("prod", tmpDir)

	infra := &entity.InfraService{
		Name: "frps-node5",
		Type: entity.InfraServiceTypeTunnelServer,
		ServiceBase: entity.ServiceBase{
			Server: "srv-node5",
		},
		Image: "docker.cnb.cool/lite-lake/app-frps-svc:prod",
		TunnelServerConfig: &entity.TunnelServerConfig{
			Ports:     entity.TunnelServerPorts{BindPort: 30070, VhostHTTPPort: 80},
			AuthToken: *valueobject.NewSecretRefSecret("frp_auth_token"),
			TunnelRoutes: []entity.TunnelRoute{
				{Hostname: "pay-dev.mesh.example.net"},
				{Hostname: "wechat-dev.mesh.example.net"},
			},
		},
	}

	config := &entity.Config{
		Secrets: []entity.Secret{{Name: "frp_auth_token", Value: "test-secret-token"}},
	}

	if err := gen.generateTunnelServerConfig(tmpDir, infra, config); err != nil {
		t.Fatalf("generateTunnelServerConfig() error = %v", err)
	}

	t.Run("frps.toml content", func(t *testing.T) {
		content, err := os.ReadFile(filepath.Join(tmpDir, "frps-node5.frps.toml"))
		if err != nil {
			t.Fatalf("failed to read frps.toml: %v", err)
		}
		s := string(content)
		checks := []string{
			"# Auto-generated by yamlops, do not edit manually",
			"bindAddr = \"0.0.0.0\"",
			"bindPort = 30070",
			"vhostHTTPPort = 80",
			"vhostHTTPSPort = 0",
			"auth.method = \"token\"",
			"auth.token = \"test-secret-token\"",
			"log.to = \"console\"",
			"log.level = \"info\"",
			"log.maxDays = 7",
			"allowPorts = []",
			"transport.tls.force = true",
		}
		for _, c := range checks {
			if !strings.Contains(s, c) {
				t.Errorf("frps.toml missing: %q", c)
			}
		}
	})

	t.Run("compose.yaml content", func(t *testing.T) {
		content, err := os.ReadFile(filepath.Join(tmpDir, "frps-node5.compose.yaml"))
		if err != nil {
			t.Fatalf("failed to read compose.yaml: %v", err)
		}
		s := string(content)
		checks := []string{
			"docker.cnb.cool/lite-lake/app-frps-svc:prod",
			"30070:30070",
			"./frps-node5.frps.toml:/app/configs/frps.toml:ro",
			"yamlops-prod",
			"host.docker.internal:host-gateway",
			"unless-stopped",
		}
		for _, c := range checks {
			if !strings.Contains(s, c) {
				t.Errorf("compose.yaml missing: %q", c)
			}
		}
	})
}

